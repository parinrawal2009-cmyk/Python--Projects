divide.grid(row=3,column=3,padx=5,pady=5)
def calculate():
    try:
        result=eval(entry.get())
        entry.delete(0,tk.END)
        entry.insert(0,result)
    except:
        entry.delete(0,tk.END)
        entry.insert(0,"Error")

equals=tk.Button(frame,text="=",width=5,height=2,font=("Arial",14),command=calculate)
equals.grid(row=4,column=0,columnspan=4,padx=5,pady=5)
clear=tk.Button(frame,text="C",width=5,height=2,font=("Arial",14),command=lambda:entry.delete(0,tk.END))
clear.grid(row=5,column=0,columnspan=4,padx=5,pady=5)
def click(number):
    entry.insert(tk.END,number)
def calculate():
    try:
        result=eval(entry.get())
        entry.delete(0,tk.END)
        entry.insert(0,result)
    except:
        entry.delete(0,tk.END)
        entry.insert(0,"Error")
